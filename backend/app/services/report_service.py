class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas to dynamically compute and draw total page numbers and header/footer."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int):
        self.saveState()
        
        # Header (pages > 1)
        if self._pageNumber > 1:
            self.setFont("Helvetica-Bold", 8)
            self.setFillColor(PRIMARY_BLUE)
            self.drawString(54, 750, "EXCEL INSIGHT")
            self.setFont("Helvetica", 8)
            self.setFillColor(SLATE_TEXT)
            self.drawString(130, 750, "|   Executive Intelligence & Data Report")
            self.setStrokeColor(BORDER_COLOR)
            self.setLineWidth(0.75)
            self.line(54, 742, 558, 742)

        # Footer (all pages)
        self.setStrokeColor(BORDER_COLOR)
        self.setLineWidth(0.75)
        self.line(54, 45, 558, 45)
        
        self.setFont("Helvetica", 8)
        self.setFillColor(SLATE_TEXT)
        self.drawString(54, 32, "Confidential — Generated by Excel Insight")
        
        page_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(558, 32, page_text)
        self.restoreState()

class ReportService:
    @staticmethod
    def _create_chart_image(chart: Dict[str, Any]) -> Optional[io.BytesIO]:
        """Generates a crisp matplotlib chart and returns BytesIO buffer."""
        chart_type = chart.get("chart_type", "bar").lower()
        title = chart.get("title", "Data Visualization")
        x_axis = chart.get("x_axis", "X")
        y_axis = chart.get("y_axis", "Y")
        data = chart.get("chart_data", [])

        if not data or len(data) == 0:
            return None

        fig, ax = plt.subplots(figsize=(6.5, 3.2), dpi=200)
        fig.patch.set_facecolor("#FFFFFF")
        ax.set_facecolor("#FAFAFA")

        # Palette
        chart_colors = ["#2563EB", "#3B82F6", "#60A5FA", "#93C5FD", "#1D4ED8", "#1E40AF"]

        if chart_type in ["bar", "stacked_bar"]:
            labels = [str(d.get("name", d.get(x_axis, "")))[:15] for d in data[:10]]
            values = [float(d.get("value", d.get(y_axis, 0)) or 0) for d in data[:10]]
            bars = ax.bar(labels, values, color="#2563EB", width=0.55, edgecolor="none")
            ax.set_ylabel(y_axis or "Value", fontsize=9, color="#475569")
            ax.tick_params(axis="x", rotation=30, labelsize=8, colors="#334155")
            ax.tick_params(axis="y", labelsize=8, colors="#334155")
            ax.spines["top"].set_visible(False)
            ax.spines["right"].set_visible(False)
            ax.spines["left"].set_color("#CBD5E1")
            ax.spines["bottom"].set_color("#CBD5E1")
            ax.yaxis.grid(True, linestyle="--", alpha=0.5, color="#E2E8F0")

        elif chart_type == "line":
            labels = [str(d.get("name", d.get(x_axis, "")))[:12] for d in data[:15]]
            values = [float(d.get("value", d.get(y_axis, 0)) or 0) for d in data[:15]]
            ax.plot(labels, values, color="#2563EB", marker="o", markersize=4, linewidth=2, label=y_axis or "Metric")
            ax.fill_between(range(len(labels)), values, color="#3B82F6", alpha=0.1)
            ax.set_ylabel(y_axis or "Value", fontsize=9, color="#475569")
            ax.tick_params(axis="x", rotation=30, labelsize=8, colors="#334155")
            ax.tick_params(axis="y", labelsize=8, colors="#334155")
            ax.spines["top"].set_visible(False)
            ax.spines["right"].set_visible(False)
            ax.yaxis.grid(True, linestyle="--", alpha=0.5, color="#E2E8F0")

        elif chart_type in ["pie", "donut"]:
            labels = [str(d.get("name", d.get(x_axis, "")))[:12] for d in data[:6]]
            values = [max(0.001, float(d.get("value", d.get(y_axis, 0)) or 0)) for d in data[:6]]
            wedgeprops = dict(width=0.4, edgecolor="white", linewidth=2) if chart_type == "donut" else dict(edgecolor="white", linewidth=1.5)
            ax.pie(
                values,
                labels=labels,
                autopct="%1.1f%%",
                startangle=140,
                colors=chart_colors[:len(values)],
                wedgeprops=wedgeprops,
                textprops={"fontsize": 8, "color": "#1E293B"}
            )
            ax.axis("equal")

        elif chart_type == "scatter":
            x_vals = [float(d.get("x", 0) or 0) for d in data[:100]]
            y_vals = [float(d.get("y", 0) or 0) for d in data[:100]]
            ax.scatter(x_vals, y_vals, color="#2563EB", alpha=0.7, edgecolors="white", s=40)
            ax.set_xlabel(x_axis, fontsize=9, color="#475569")
            ax.set_ylabel(y_axis or "Value", fontsize=9, color="#475569")
            ax.grid(True, linestyle="--", alpha=0.5, color="#E2E8F0")

        else: # Default bar
            labels = [str(d.get("name", ""))[:12] for d in data[:10]]
            values = [float(d.get("value", 0) or 0) for d in data[:10]]
            ax.bar(labels, values, color="#2563EB", width=0.5)

        ax.set_title(title, fontsize=10, fontweight="bold", color="#0F172A", pad=12)
        plt.tight_layout()

        buf = io.BytesIO()
        plt.savefig(buf, format="png", dpi=200, bbox_inches="tight")
        plt.close(fig)
        buf.seek(0)
        return buf

    @classmethod
    def generate_pdf_report(
        cls,
        report_meta: Dict[str, Any],
        analysis_data: Dict[str, Any],
        output_stream: io.BytesIO
    ) -> None:
        doc = SimpleDocTemplate(
            output_stream,
            pagesize=letter,
            leftMargin=54,
            rightMargin=54,
            topMargin=54,
            bottomMargin=54
        )

        styles = getSampleStyleSheet()
        
        # Custom styles
        title_style = ParagraphStyle(
            "DocTitle",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=24,
            leading=28,
            textColor=DARK_NAVY,
            spaceAfter=6
        )
        subtitle_style = ParagraphStyle(
            "DocSubtitle",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=11,
            leading=16,
            textColor=SLATE_TEXT,
            spaceAfter=15
        )
        h1_style = ParagraphStyle(
            "Heading1_Custom",
            parent=styles["Heading1"],
            fontName="Helvetica-Bold",
            fontSize=14,
            leading=18,
            textColor=DARK_NAVY,
            spaceBefore=12,
            spaceAfter=8
        )
        h2_style = ParagraphStyle(
            "Heading2_Custom",
            parent=styles["Heading2"],
            fontName="Helvetica-Bold",
            fontSize=11,
            leading=15,
            textColor=PRIMARY_BLUE,
            spaceBefore=8,
            spaceAfter=4
        )
        body_style = ParagraphStyle(
            "Body_Custom",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=9.5,
            leading=14,
            textColor=SLATE_TEXT,
            spaceAfter=6
        )
        callout_style = ParagraphStyle(
            "Callout",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=10,
            leading=15,
            textColor=DARK_NAVY
        )

        elements: List[Any] = []

        # ==========================================
        # 1. Header Banner & Document Meta
        # ==========================================
        elements.append(Paragraph(report_meta.get("title", "Excel Insight Executive Report"), title_style))
        gen_time = datetime.now().strftime("%B %d, %Y - %H:%M WIB")
        elements.append(Paragraph(
            f"<b>Generated:</b> {gen_time} &nbsp;&nbsp;|&nbsp;&nbsp; <b>Sheet:</b> {analysis_data.get('sheet_name', 'Default')}",
            subtitle_style
        ))
        elements.append(HRFlowable(width="100%", thickness=1.5, color=PRIMARY_BLUE, spaceAfter=15))

        # ==========================================
        # 2. Executive Summary Callout Box
        # ==========================================
        exec_summary = report_meta.get("executive_summary") or "This report compiles automated exploratory data analysis, dataset quality validation, statistical distributions, and visual analytics derived directly from uploaded spreadsheet records."
        summary_cell = [
            Paragraph("<b>EXECUTIVE SUMMARY</b>", h2_style),
            Spacer(1, 4),
            Paragraph(exec_summary, callout_style)
        ]
        summary_table = Table([[summary_cell]], colWidths=[504])
        summary_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), LIGHT_BG),
            ("BOX", (0, 0), (-1, -1), 1, BORDER_COLOR),
            ("LINELEFT", (0, 0), (-1, -1), 3.5, PRIMARY_BLUE),
            ("TOPPADDING", (0, 0), (-1, -1), 10),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 10),
            ("LEFTPADDING", (0, 0), (-1, -1), 14),
            ("RIGHTPADDING", (0, 0), (-1, -1), 14),
        ]))
        elements.append(summary_table)
        elements.append(Spacer(1, 14))

        # ==========================================
        # 3. Dataset Characteristics & Quality Audit
        # ==========================================
        elements.append(Paragraph("Dataset Overview & Quality Health", h1_style))
        q_summary = analysis_data.get("quality_summary", {})
        row_count = analysis_data.get("row_count", 0)
        col_count = analysis_data.get("column_count", 0)
        completeness = q_summary.get("completeness_score", 100.0)
        dupes = q_summary.get("duplicate_rows", 0)
        missing_cells = q_summary.get("missing_cells", 0)
        grade = q_summary.get("quality_grade", "Good")

        overview_data = [
            ["Metric", "Value", "Quality Assessment", "Status"],
            ["Total Rows", f"{row_count:,}", "Dataset size volume", "Analyzed"],
            ["Total Columns", str(col_count), "Feature dimensionality", "Mapped"],
            ["Completeness Score", f"{completeness}%", f"{missing_cells} missing values detected", grade],
            ["Duplicate Records", str(dupes), f"{q_summary.get('duplicate_percentage', 0)}% of dataset", "Verified"],
        ]
        t_overview = Table(overview_data, colWidths=[120, 100, 200, 84])
        t_overview.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), DARK_NAVY),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, 0), 8.5),
            ("ALIGN", (0, 0), (-1, -1), "LEFT"),
            ("ALIGN", (1, 0), (1, -1), "CENTER"),
            ("ALIGN", (3, 0), (3, -1), "CENTER"),
            ("FONTNAME", (0, 1), (-1, -1), "Helvetica"),
            ("FONTSIZE", (0, 1), (-1, -1), 8.5),
            ("TEXTCOLOR", (0, 1), (-1, -1), SLATE_TEXT),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, LIGHT_BG]),
            ("GRID", (0, 0), (-1, -1), 0.5, BORDER_COLOR),
            ("TOPPADDING", (0, 0), (-1, -1), 6),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ]))
        elements.append(t_overview)
        elements.append(Spacer(1, 14))

        # ==========================================
        # 4. Key Findings Section
        # ==========================================
        key_findings = report_meta.get("key_findings", [])
        if key_findings:
            elements.append(Paragraph("Key Analytical Observations", h1_style))
            for finding in key_findings:
                bullet_text = f"• &nbsp; {finding}"
                elements.append(Paragraph(bullet_text, body_style))
            elements.append(Spacer(1, 10))

        # ==========================================
        # 5. Visual Charts Section
        # ==========================================
        selected_charts = report_meta.get("selected_charts", [])
        if selected_charts:
            elements.append(Paragraph("Analytical Visualizations", h1_style))
            for i, ch in enumerate(selected_charts):
                img_buf = cls._create_chart_image(ch)
                if img_buf:
                    chart_elements = []
                    chart_title = ch.get("title", f"Visualization {i+1}")
                    chart_elements.append(Paragraph(f"<b>Figure {i+1}:</b> {chart_title}", h2_style))
                    chart_img = Image(img_buf, width=6.5*inch, height=3.2*inch)
                    chart_elements.append(chart_img)
                    
                    insight = ch.get("insight") or f"Visualizes {ch.get('y_axis', 'metric')} aggregated by {ch.get('x_axis', 'dimension')} ({ch.get('chart_type', 'bar').upper()})."
                    chart_elements.append(Paragraph(f"<i>Insight:</i> {insight}", body_style))
                    chart_elements.append(Spacer(1, 12))
                    
                    # Prevent splitting figure and description across pages
                    elements.append(KeepTogether(chart_elements))

        # Build document with custom canvas
        doc.build(elements, canvasmaker=NumberedCanvas)

report_service = ReportService()
